#!/usr/bin/env python3
"""Writes docs/url-map.md: every old www.gymskutec.cz address found in docs/source-inventory*.md and where it lands on the
built site (same address, 301 from vercel.json, or missing). Run after build.py; exits non-zero if any address is unmapped.
With --live PORT it also requests every old address from `build.py serve PORT` and checks status and target."""
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
FILES = re.compile(r"(e_download|evt_file|evt_image|download\.php|/data/|/skins/)")
V = json.loads((ROOT / "vercel.json").read_text())


def exists(path):
    f = DIST / unquote(path).lstrip("/")
    return f.is_file() or (f / "index.html").is_file()


def resolve(u):
    path, _, q = u.partition("?")
    for r in V["redirects"]:
        if r.get("has"):
            if path == r["source"] and q and re.search(rf"(^|&){r['has'][0]['key']}(=|&|$)", q):
                return r["destination"], "301"
        elif r["source"] == path or (r["source"].endswith(":path*") and path.startswith(r["source"][:-6])):
            return r["destination"], "301"
    return (path, "same") if exists(path) else (None, "missing")


def main():
    text = "".join(p.read_text(encoding="utf-8") for p in sorted((ROOT / "docs").glob("source-inventory*.md")))
    urls = sorted({u.rstrip(".;:").split("#")[0] for u in re.findall(r'https?://(?:www\.)?gymskutec\.cz(/[^\s)\]>"`,]*)', text) if not FILES.search(u)})
    rows = [(u, *resolve(u)) for u in urls]
    miss = [u for u, _, k in rows if k == "missing"]
    same = sum(k == "same" for *_, k in rows)
    body = "\n".join(f"| `{u}` | {'`' + n + '`' if n else '—'} | {k} |" for u, n, k in rows)
    (ROOT / "docs" / "url-map.md").write_text(f"""# Legacy URL map

Generated by `tools/url_map.py` from the two crawls of the old www.gymskutec.cz (`docs/source-inventory*.md`), checked against the built site.
File addresses (`e_download.php`, `evt_file.php`, `evt_image.php`, `modules/file_storage/…`, `/data/…`) are handled by `tools/migrate_files.py`.

- **same**: the page exists at the same address ({same} of {len(rows)}).
- **301**: permanent redirect in `vercel.json` ({len(rows) - same - len(miss)}).
- **missing**: no page and no redirect ({len(miss)}).

| Old URL | New URL | |
|---|---|---|
{body}
""", encoding="utf-8")
    print(f"{len(rows)} old URLs: {same} same, {len(rows) - same - len(miss)} redirected, {len(miss)} missing")
    for m in miss:
        print("MISSING", m)
    bad = 0
    if "--live" in sys.argv:
        port = sys.argv[sys.argv.index("--live") + 1]
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, *a, **k): return None
        opener = urllib.request.build_opener(NoRedirect)
        for u, n, k in rows:
            if k == "missing" or "?" in u and k == "301" and any(r.get("has") for r in V["redirects"] if r["destination"] == n):
                continue  # query-string rules exist on Vercel only
            try:
                code, loc = opener.open(f"http://127.0.0.1:{port}{u}").status, None
            except urllib.error.HTTPError as e:
                code, loc = e.code, e.headers.get("Location")
            ok = (code == 200) if k == "same" else (code == 301 and loc == n)
            if not ok:
                bad += 1
                print("LIVE FAIL", u, code, loc)
        print(f"live check: {len(rows) - bad} ok, {bad} failed")
    sys.exit(1 if miss or bad else 0)


if __name__ == "__main__":
    main()
